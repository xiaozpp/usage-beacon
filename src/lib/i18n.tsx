type TranslationValues = Record<string, string | number>;

interface I18nContextValue {
  language: AppLanguage;
  locale: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

function isLanguage(value: string | null): value is AppLanguage {
  return value === "zh-CN" || value === "en-US";
}

function readStoredLanguage(): AppLanguage | null {
  if (typeof window === "undefined") return null;
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return isLanguage(stored) ? stored : null;
  } catch {
    return null;
  }
}

function detectLanguage(): AppLanguage {
  const stored = readStoredLanguage();
  if (stored) return stored;
  if (typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("zh")) {
    return "zh-CN";
  }
  return "en-US";
}

function applyLanguage(language: AppLanguage) {
  if (typeof document !== "undefined") {
    document.documentElement.lang = language;
    document.documentElement.dataset.language = language;
    document.title = language === "zh-CN"
      ? "Usage Beacon · 使用统计"
      : "Usage Beacon · Usage Analytics";
  }
}

function saveLanguage(language: AppLanguage) {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  } catch {
    // A restricted WebView may not expose localStorage; language still works for this session.
  }
}

function interpolate(template: string, values?: TranslationValues): string {
  if (!values) return template;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.split("{{" + key + "}}").join(String(value)),
    template,
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => {
    const initial = detectLanguage();
    applyLanguage(initial);
    return initial;
  });

  const setLanguage = useCallback((next: AppLanguage) => {
    applyLanguage(next);
    saveLanguage(next);
    setLanguageState(next);
  }, []);

  useEffect(() => {
    applyLanguage(language);
  }, [language]);

  const value = useMemo<I18nContextValue>(() => {
    const messages = language === "zh-CN" ? zh : en;
    return {
      language,
      locale: language,
      setLanguage,
      t: (key, values) => interpolate(messages[key] ?? zh[key], values),
    };
  }, [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
